test('capability limita o PR e a conta e não pode ser reutilizada após sucesso', async () => {
  const e = engineForPost();
  const posted = [];
  e.postReview = async (pr, reviewPayload) => {
    if (/gerada automaticamente/i.test(reviewPayload.body)) {
      return { ok: false, blocked: 'internal_language', error: 'ajuste a redação' };
    }
    posted.push({ pr, reviewPayload });
    return { ok: true };
  };
  e.reconcilePending = async () => 0;
  const cap = e.createReviewPostCapability(['acme/app#90'], 'conta-da-sessao', 'chat', 'chat-1');

  const outside = await e.postReviewFromSession({ key: 'acme/app#91', payload: payload('ok') }, cap);
  assert.equal(outside.ok, false);
  assert.equal(outside.blocked, 'capability');
  assert.equal(posted.length, 0, 'tentativa fora do escopo não consome nem posta');

  const locallyBlocked = await e.postReviewFromSession({
    key: 'acme/app#90', payload: payload('Esta revisão foi gerada automaticamente pelo Farol.'),
  }, cap);
  assert.equal(locallyBlocked.ok, false);
  assert.equal(locallyBlocked.blocked, 'internal_language');
  assert.equal(posted.length, 0, 'bloqueio local não chama o GitHub');

  const first = await e.postReviewFromSession({ key: 'acme/app#90', payload: payload('ok') }, cap);
  assert.equal(first.ok, true);
  assert.equal(posted.length, 1);
  assert.equal(posted[0].pr.key, 'acme/app#90');
  assert.equal(posted[0].pr.account, 'conta-da-sessao', 'identidade vem da capability, não do envelope');

  const reused = await e.postReviewFromSession({ key: 'acme/app#90', payload: payload('ok de novo') }, cap);
  assert.equal(reused.ok, false);
  assert.equal(reused.blocked, 'capability');
  assert.equal(posted.length, 1, 'capability permite corrigir bloqueio local, mas é one-shot após sucesso');
});

test('duas submissões concorrentes com a mesma capability e key chamam o writer uma vez', async () => {
  const e = engineForPost();
  e.reconcilePending = async () => 0;
  const cap = e.createReviewPostCapability(['acme/app#92'], 'eu', 'chat', 'chat-race');
  let releaseFirst;
  const firstGate = new Promise(resolve => { releaseFirst = resolve; });
  let postCalls = 0;
  e.postReview = async () => {
    postCalls++;
    if (postCalls === 1) await firstGate;
    return { ok: true };
  };

  const first = e.postReviewFromSession({ key: 'acme/app#92', payload: payload('primeiro') }, cap);
  await new Promise(resolve => setImmediate(resolve));
  const second = e.postReviewFromSession({ key: 'acme/app#92', payload: payload('segundo') }, cap);
  await new Promise(resolve => setImmediate(resolve));
  releaseFirst();
  const results = await Promise.all([first, second]);

  assert.equal(postCalls, 1, 'a key precisa ser reservada antes do await do writer');
  assert.equal(results.filter(r => r.ok).length, 1);
  assert.equal(results.filter(r => r.blocked === 'capability').length, 1);
});

