test('regressão #161: bloqueia o template e a frase que vazaram no review público real', () => {
  // Recorte literal do APPROVE publicado em biudtech/biud-esg#161. Manter a
  // combinação importa: ela cobre tanto a voz de template quanto a revelação
  // da decisão automática que escapou no último parágrafo.
  const body = [
    '> [!NOTE]',
    '> **✅ APPROVE** — propagação real de 2026-07 (aprovado e mergeado em #160), sem blocker.',
    '',
    '**Placar:** 🔴 0 · 🟡 1 · ❓ 0 · 🟢 4',
    '- [x] CPF lido do path param; a query string deixa de ser lida',
    '',
    'Ainda não dá pra confirmar verde — por isso não auto-aprovei.',
  ].join('\n');

  const issues = publicReview.publicReviewLanguageIssues(payload(body));
  assert.deepEqual([...new Set(issues.map(x => x.field))], ['body']);
  const expectedCodes = ['robotic_alert', 'robotic_scoreboard', 'robotic_checklist', 'auto_decision'];
  assert.deepEqual(
    expectedCodes.filter(code => !issues.some(x => x.code === code)),
    [],
    'todas as assinaturas do vazamento real precisam ser detectadas'
  );
});

